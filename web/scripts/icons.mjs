// Writes src/lib/icons.ts, the icons PagerArchive uses (R77a, ADR 0015),
// from the pinned @tabler/icons package, with its MIT notice. Each icon is
// keyed by what it means, so one icon means one thing everywhere.
//
// usage: node scripts/icons.mjs [--check]
// --check: fail if src/lib/icons.ts isn't what this would write (CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const web = fileURLToPath(new URL('..', import.meta.url));
const pkg = `${web}node_modules/@tabler/icons/`;
const out = `${web}src/lib/icons.ts`;

// Meaning: Tabler outline icon.
const icons = {
	messages: 'message',
	map: 'map',
	jobs: 'clipboard-list',
	tools: 'tool',
	reports: 'chart-bar',
	account: 'user-circle',
	administration: 'shield',
	print: 'printer',
	integrations: 'webhook',
	users: 'users',
	templates: 'template',
	clients: 'antenna',
	unknown: 'help-circle',
	profile: 'user',
	requests: 'inbox',
	invite: 'user-plus',
	aliases: 'tag',
	retention: 'history',
	waiting: 'list-check',
	backups: 'cloud-check',
	hosts: 'server',
	search: 'search',
	help: 'info-circle',
	shrink: 'layout-sidebar-left-collapse',
	widen: 'layout-sidebar-left-expand',
	open: 'chevron-down',
	closed: 'chevron-right',
	more: 'dots',
	close: 'x',
	back: 'arrow-left',
	heartbeat: 'heartbeat',
	link: 'link',
	calendar: 'calendar',
	auto: 'device-desktop',
	light: 'sun',
	dark: 'moon',
	location: 'map-pin',
	list: 'list',
	warning: 'alert-triangle',
	signout: 'logout',
	// M21: the search box's Clear all, and the calendar's months (R33a).
	clear: 'filter-x',
	previous: 'caret-left',
	next: 'caret-right'
};

const version = JSON.parse(readFileSync(`${pkg}package.json`, 'utf8')).version;
const licence = readFileSync(`${pkg}LICENSE`, 'utf8').trim();

/** The drawing inside an icon's <svg>, without Tabler's invisible box. */
function inner(name) {
	const svg = readFileSync(`${pkg}icons/outline/${name}.svg`, 'utf8');
	const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
	return body
		.replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
		.split('\n')
		.map((l) => l.trim())
		.filter(Boolean)
		.join('');
}

const lines = [
	`/*! Icons from Tabler Icons ${version} (outline), https://tabler.io/icons`,
	' *',
	...licence.split('\n').map((l) => (l ? ` * ${l}` : ' *')),
	' */',
	'',
	'// Generated by scripts/icons.mjs from the pinned @tabler/icons package: do',
	'// not edit by hand. Each value is the inner markup of a 24 x 24 outline SVG,',
	'// drawn with currentColor (R77a, ADR 0015).',
	'export const icons = {',
	...Object.entries(icons).map(([k, v]) => `\t${k}: '${inner(v)}',`),
	'} as const;',
	'',
	'export type IconName = keyof typeof icons;',
	''
];
const text = lines.join('\n').replace(/,\n\} as const/, '\n} as const');

if (process.argv.includes('--check')) {
	let have = '';
	try {
		have = readFileSync(out, 'utf8');
	} catch {
		// missing: different
	}
	if (have !== text) {
		console.error('src/lib/icons.ts is not what scripts/icons.mjs writes from @tabler/icons: run `node scripts/icons.mjs`');
		process.exit(1);
	}
	console.log(`src/lib/icons.ts: ${Object.keys(icons).length} icons, as generated from @tabler/icons ${version}`);
} else {
	writeFileSync(out, text);
	console.log(`wrote src/lib/icons.ts: ${Object.keys(icons).length} icons from @tabler/icons ${version}`);
}
