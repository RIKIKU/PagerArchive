//go:build ignore

// Generates the example network's address dataset and the GeoJSON for its
// tiny test map (ADR 0005). Every street and locality is made up, and they
// sit in open ocean in the South Pacific (UTM zone 7 south), so the example
// is at a neutral location (SPEC.md section 14).
//
// usage: go run ./scripts/example-map
//
// Then rebuild the test map with scripts/example-map/build-tiles.sh.
package main

import (
	"encoding/json"
	"fmt"
	"math"
	"os"

	"github.com/RIKIKU/PagerArchive/internal/geo"
)

const zone = 7

type street struct {
	name, locality string
	numbers        []string
	at             func(i int) (e, n float64) // UTM position of the i-th number
	from, to       [2]float64                 // line drawn on the test map
	kind           string                     // road kind on the test map
}

func seq(from, to, step int) []string {
	var out []string
	for i := from; i <= to; i += step {
		out = append(out, fmt.Sprint(i))
	}
	return out
}

// 12 FICTION ST, MADEUPTON is in the 100 m cell of grid reference 123456
// (07HEB 123 456), so example golden row 1's address and grid agree.
const fictionE, fictionN = 512350.0, 6145650.0

var streets = []street{
	{name: "FICTION ST", locality: "MADEUPTON", numbers: seq(1, 20, 1), kind: "minor_road",
		at: func(i int) (float64, float64) {
			k := float64(i + 1)
			side := 15.0
			if int(k)%2 == 0 {
				side = -15
			}
			if k == 12 {
				side = 0
			}
			return fictionE + (k-12)*20, fictionN + side
		},
		from: [2]float64{fictionE - 260, fictionN}, to: [2]float64{fictionE + 200, fictionN}},
	{name: "EXAMPLE ST", locality: "MADEUPTON", numbers: seq(1, 12, 1), kind: "minor_road",
		at:   func(i int) (float64, float64) { return 512615 + float64(i%2)*30, 6145350 + float64(i)*45 },
		from: [2]float64{512630, 6145300}, to: [2]float64{512630, 6145900}},
	// A long rural road: no house number on golden row 2, so it's placed at
	// the street's centroid and marked approximate (section 14).
	{name: "SAMPLE RD", locality: "MADEUPTON", numbers: seq(50, 400, 50), kind: "major_road",
		at:   func(i int) (float64, float64) { return 510500 + float64(i)*500, 6146480 },
		from: [2]float64{510000, 6146500}, to: [2]float64{514200, 6146500}},
	{name: "DEMO PL", locality: "MADEUPTON", numbers: seq(1, 6, 1), kind: "minor_road",
		at:   func(i int) (float64, float64) { return 511800 + float64(i%2)*25 - 12, 6145700 + float64(i/2)*50 },
		from: [2]float64{511800, fictionN}, to: [2]float64{511800, 6145860}},
	// Same street name in another locality, 20 km north.
	{name: "FICTION ST", locality: "TESTVILLE", numbers: seq(1, 10, 1), kind: "minor_road",
		at:   func(i int) (float64, float64) { return 512000 + float64(i)*25, 6165650 + float64(i%2)*20 - 10 },
		from: [2]float64{511950, 6165650}, to: [2]float64{512300, 6165650}},
}

func round(v float64) float64 { return math.Round(v*1e6) / 1e6 }

func point(e, n float64) geo.Point {
	p := geo.FromUTM(zone, true, e, n)
	return geo.Point{Lon: round(p.Lon), Lat: round(p.Lat)}
}

type address struct {
	Number   string  `json:"number"`
	Street   string  `json:"street"`
	Locality string  `json:"locality"`
	Lon      float64 `json:"lon"`
	Lat      float64 `json:"lat"`
}

type feature struct {
	Type       string         `json:"type"`
	Properties map[string]any `json:"properties"`
	Geometry   map[string]any `json:"geometry"`
}

func main() {
	type entry struct {
		Street   string `json:"street"`
		Locality string `json:"locality"`
	}
	ds := struct {
		Schema    string    `json:"$schema"`
		Comment   string    `json:"_comment"`
		Attr      string    `json:"attribution"`
		Streets   []entry   `json:"streets"`
		Addresses []address `json:"addresses"`
	}{
		Schema:  "../../schemas/address-dataset.schema.json",
		Comment: "Small made-up address dataset for the example network. Every street and locality is invented, and they sit in open ocean (SPEC.md section 14). Generated by scripts/example-map/main.go.",
		Attr:    "Example address data, made up for PagerArchive",
	}
	var roads, places []feature
	for _, s := range streets {
		ds.Streets = append(ds.Streets, entry{s.name, s.locality})
		for i, num := range s.numbers {
			p := point(s.at(i))
			ds.Addresses = append(ds.Addresses, address{num, s.name, s.locality, p.Lon, p.Lat})
		}
		a, b := point(s.from[0], s.from[1]), point(s.to[0], s.to[1])
		roads = append(roads, feature{"Feature", map[string]any{"kind": s.kind, "name": s.name, "min_zoom": 10},
			map[string]any{"type": "LineString", "coordinates": [][2]float64{{a.Lon, a.Lat}, {b.Lon, b.Lat}}}})
	}
	for _, pl := range []struct {
		name string
		e, n float64
	}{{"MADEUPTON", 512300, 6145900}, {"TESTVILLE", 512100, 6165900}} {
		name, p := pl.name, point(pl.e, pl.n)
		places = append(places, feature{"Feature", map[string]any{"kind": "locality", "name": name, "min_zoom": 8, "population_rank": 5},
			map[string]any{"type": "Point", "coordinates": [2]float64{p.Lon, p.Lat}}})
	}
	// Made-up land under both localities, so the map isn't all ocean.
	var earth []feature
	for _, box := range [][4]float64{{508500, 6144000, 516000, 6148500}, {510500, 6164500, 514000, 6167000}} {
		sw, se, ne, nw := point(box[0], box[1]), point(box[2], box[1]), point(box[2], box[3]), point(box[0], box[3])
		earth = append(earth, feature{"Feature", map[string]any{"kind": "earth"}, map[string]any{"type": "Polygon",
			"coordinates": [][][2]float64{{{sw.Lon, sw.Lat}, {se.Lon, se.Lat}, {ne.Lon, ne.Lat}, {nw.Lon, nw.Lat}, {sw.Lon, sw.Lat}}}}})
	}
	write("profiles/example/example-addresses.json", ds)
	for layer, fs := range map[string][]feature{"roads": roads, "places": places, "earth": earth} {
		write("deploy/example-map/"+layer+".geojson", map[string]any{"type": "FeatureCollection", "features": fs})
	}
}

func write(path string, v any) {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, append(data, '\n'), 0o644); err != nil {
		panic(err)
	}
}
